import { AssetItem, AnomalySeverity } from '../types';

export function calculateAnomalies(item: {
  category: string;
  subCategory: string;
  cost: number;
  acquiredYearBE: number;
  description: string;
  name: string;
}): { anomalies: string[]; severity: AnomalySeverity } {
  const anomalies: string[] = [];
  let severity: AnomalySeverity = 'none';
  const currentYearBE = 2569;
  const ageYears = currentYearBE - item.acquiredYearBE;

  // 1. Check expired or high lifespan
  if (
    (item.subCategory.includes('คอมพิวเตอร์') || item.name.includes('คอมพิวเตอร์') || item.name.includes('โน้ตบุ๊ค')) &&
    ageYears >= 5
  ) {
    anomalies.push(`อายุการใช้งานคอมพิวเตอร์เกิน 5 ปี (${ageYears} ปี) เสี่ยงเสื่อมสภาพ/ตกรุ่น`);
    severity = 'medium';
  } else if (item.subCategory.includes('ยานพาหนะ') && ageYears >= 10) {
    anomalies.push(`อายุการใช้งานยานพาหนะเกิน 10 ปี (${ageYears} ปี) ควรตรวจสภาพความปลอดภัยพิเศษ`);
    severity = 'high';
  } else if (ageYears >= 15 && !item.category.includes('สิ่งปลูกสร้าง') && !item.category.includes('อาคาร')) {
    anomalies.push(`อายุการใช้งานสูงเกินเกณฑ์ทั่วไป (${ageYears} ปี) ควรพิจารณาจำหน่าย/ซ่อมบำรุง`);
    severity = severity === 'none' ? 'medium' : severity;
  }

  // 2. High valuation alert
  if (item.cost >= 10000000) {
    anomalies.push(`ทรัพย์สินมูลค่าสูงพิเศษ (>= 10 ล้านบาท) ต้องมีคณะกรรมการตรวจนับสถานที่จริง`);
    severity = 'critical';
  } else if (item.cost >= 1000000) {
    anomalies.push(`ทรัพย์สินมูลค่าสูง (>= 1 ล้านบาท) ควรมีภาพถ่ายและพิกัดตรวจสอบ`);
    severity = 'high';
  }

  // 3. Public safety / Children playground
  if (item.name.includes('เครื่องเล่น') || item.name.includes('สไลเดอร์') || item.name.includes('สระว่ายน้ำ')) {
    anomalies.push(`เครื่องเล่น/พื้นที่สาธารณะ ต้องตรวจความแข็งแรงโครงสร้างเพื่อความปลอดภัยเด็ก`);
    if (severity === 'none') severity = 'medium';
  }

  // 4. Missing serial for high-tech electronics
  if (
    (item.name.includes('คอมพิวเตอร์') || item.name.includes('โน้ตบุ๊ค') || item.name.includes('โทรทัศน์')) &&
    !item.description.toLowerCase().includes('s/n') &&
    !item.description.includes('หมายเลขเครื่อง')
  ) {
    anomalies.push(`ไม่ระบุ Serial Number หรือหมายเลขเครื่องในรายละเอียด`);
    if (severity === 'none') severity = 'low';
  }

  return { anomalies, severity };
}

